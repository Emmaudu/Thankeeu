<h2>Matching the Message to the Relationship</h2>

<p>The right tone depends heavily on how close you are to the recipient. A close friend can handle a joke-heavy, informal message. A more distant colleague or acquaintance usually calls for something warmer but slightly more measured - genuine, but not overly familiar. When in doubt, lean toward sincerity over humour; a message that tries too hard to be funny for someone you do not know especially well can land awkwardly, while a slightly formal but warm message rarely does.</p>

