<h2>A Few Quick Questions People Often Have</h2>

<p><strong>Is it rude to send an eCard instead of a physical card?</strong> No - what matters far more than the format is whether the message itself is genuine and specific. A thoughtful eCard beats a generic physical one every time.</p>

<p><strong>Should I sign off with my full name or just my first name?</strong> This depends entirely on the relationship and context. For close friends and family, a first name is fine. For a workplace card or a message to someone who might not immediately recognise the sender, a full name avoids any confusion.</p>

<p><strong>How long should a message actually be?</strong> Long enough to say something specific, short enough that it does not feel like it is padding for length. Two to four genuine sentences usually beats a long paragraph that dilutes the actual sentiment.</p>

