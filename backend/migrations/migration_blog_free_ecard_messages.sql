<h2>Common Mistakes When Writing eCard Messages</h2>

<p>Beyond finding the right words, a few habits consistently weaken an otherwise good message.</p>

<h3>Starting with an apology for lateness</h3>
<p>"Sorry this is late but..." undercuts the message before it even begins. If the timing is off, either leave it out entirely or address it briefly and move straight into the actual message. Dwelling on it draws more attention to the delay than the recipient would otherwise notice.</p>

<h3>Making it about you instead of them</h3>
<p>It is easy to accidentally centre a message on your own feelings rather than the recipient''s moment. "I cannot believe how busy I have been, but I wanted to say happy birthday" spends more words on your schedule than on them. Keep the focus on the person the card is for.</p>

<h3>Over-explaining a joke or reference</h3>
<p>If a message needs three sentences of context before the actual joke lands, it usually is not worth including in written form. Save longer stories for a phone call or an in-person conversation, and keep the card message itself short and clear.</p>

<h3>Copying a message verbatim from a list like this one</h3>
<p>These messages work well as starting points, but a recipient who has seen the same phrasing before - from a different card, a different year, a different person - will notice. Even a small tweak, one added detail, changes a generic line into something that reads as genuinely yours.</p>

