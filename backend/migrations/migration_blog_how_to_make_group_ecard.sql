<h2>A Quick Checklist Before You Share the Link</h2>

<p>Before sending the link out to your group, run through this short checklist to avoid the most common setup mistakes:</p>

<ul>
<li>Is the delivery date and time set correctly, including the right time zone if your group spans multiple regions?</li>
<li>Have you given people at least a few days to sign, rather than a same-day deadline?</li>
<li>If gift collection is enabled, is the target amount or purpose clear to signers?</li>
<li>Does your invitation message give people a starting point ("share a memory" or "just say what you will miss") rather than a completely blank instruction?</li>
<li>Have you included everyone who should be invited, including remote or hybrid colleagues who might otherwise be missed?</li>
</ul>

