// Builds src/content/countries/index.js: a small summary of every country's
// pages (services, cities, comparisons) for the navbar, footer, sitemaps and
// prerender, so those never have to load the full page content.
// Run: node scripts/build-country-index.mjs (also runs before every build).
import { writeFileSync } from 'fs';
import { dirname, join } from 'path';
import { fileURLToPath } from 'url';
const here = dirname(fileURLToPath(import.meta.url));
const SLUGS = ['us', 'uk', 'ireland', 'australia', 'new-zealand', 'canada', 'singapore'];
const out = {};
for (const slug of SLUGS) {
  const c = (await import(join(here, '../src/content/countries', `${slug}.js`))).default;
  out[slug] = {
    slug, name: c.name, regions: c.regions,
    services: c.services.map((s) => ({ slug: s.slug, name: s.name })),
    cities: c.cities.map((s) => ({ slug: s.slug, name: s.name })),
    compare: c.compare.map((s) => ({ slug: s.slug, competitor: s.competitor })),
  };
}
writeFileSync(join(here, '../src/content/countries/index.js'),
  '// GENERATED by scripts/build-country-index.mjs. Do not edit by hand.\nexport default ' + JSON.stringify(out) + ';\n');
console.log('country index written:', SLUGS.map((s) => `${s} ${out[s].services.length}/${out[s].cities.length}/${out[s].compare.length}`).join(', '));
